function convertRawToWord(item: LukeRawWord, index: number): GreekWord {
  const phonetics = convertGreekToErasmianPhonetics(item.lemma);
  const chapterNum = item.chapterNumber;
  const greekForm = item.lemma;
  const mnemonic = getMnemonicForWord({ greek: greekForm, lemma: item.lemma, translationRu: item.translation });

  return {
    id: `luke${chapterNum}_w_${index + 1}`,
    greek: greekForm,
    lemma: item.lemma,
    transliterationRu: phonetics,
    erasmianIpa: phonetics,
    partOfSpeech: (item.partOfSpeech || 'noun') as any,
    gender: item.gender as any,
    article: item.article,
    translationRu: item.translation,
    additionalMeaningsRu: [item.translation],
    ntFrequency: item.frequency,
    frequencyCategory: item.frequency >= 50 ? '50-100' : item.frequency >= 20 ? '20-50' : item.frequency >= 10 ? '10-20' : '<10',
    thematicGroup: 'theology_church',
    thematicGroupNameRu: 'Евангелие от Луки',
    chapters: [`luke_${chapterNum}`],
    exampleVerse: {
      reference: item.verseRef,
      greekText: item.contextPhrase,
      translationRu: item.contextRu,
      highlightWord: item.lemma,
    },
    erasmianNotes: 'Эразмово произношение: точное ударение и аутентичная артикуляция дифтонгов и согласных.',
    mnemonicRu: mnemonic,
    morphologyNotes: item.displayLemma !== item.lemma ? item.displayLemma : undefined,
  };
}

