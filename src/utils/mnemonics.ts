/**
 * Returns a mnemonic association for a given Greek lemma or word
 */
export function getMnemonicForWord(
  word: { greek: string; lemma?: string; translationRu?: string; id?: string },
  customMnemonics?: Record<string, string>
): string | undefined {
  if (!word) return undefined;
  
  if (word.id && customMnemonics && customMnemonics[word.id]) {
    return customMnemonics[word.id];
  }

  const cleanGreek = word.greek ? word.greek.split(/[,(\s]/)[0].trim() : '';
  const cleanLemma = word.lemma ? word.lemma.split(/[,(\s]/)[0].trim() : '';

  if (cleanGreek && MNEMONICS_MAP[cleanGreek]) return MNEMONICS_MAP[cleanGreek];
  if (cleanLemma && MNEMONICS_MAP[cleanLemma]) return MNEMONICS_MAP[cleanLemma];

  // Try normalized search without accents
  const strip = (s: string) => s.normalize('NFD').replace(/[\u0300-\u036F]/g, '').toLowerCase();
  const targetGreek = strip(cleanGreek);
  const targetLemma = strip(cleanLemma);

  for (const [key, val] of Object.entries(MNEMONICS_MAP)) {
    const keyClean = strip(key);
    if (keyClean === targetGreek || keyClean === targetLemma) {
      return val;
    }
  }

  return undefined;
}
