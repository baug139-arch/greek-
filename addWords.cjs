function parseTags(tagsStr) {
  const parts = tagsStr.split('/').map(s => s.trim());
  let pos = '';
  let gender = undefined;
  let number = undefined;
  let caseVal = undefined;
  
  if (parts[0] === 'Сущ.') pos = 'noun';
  if (parts[0] === 'Прилаг.') pos = 'adjective';
  
  for (let p of parts) {
    if (['Муж.', 'Жен.', 'Ср.', 'Все роды', 'Муж.-Ср.'].includes(p)) {
      if (p === 'Муж.') gender = 'm';
      if (p === 'Жен.') gender = 'f';
      if (p === 'Ср.') gender = 'n';
      if (p === 'Все роды') gender = ['m', 'f', 'n'];
      if (p === 'Муж.-Ср.') gender = ['m', 'n'];
    }
    if (['Ед.ч.', 'Мн.ч.'].includes(p)) {
      if (p === 'Ед.ч.') number = 'sg';
      if (p === 'Мн.ч.') number = 'pl';
    }
    if (p.includes('Им.п.') || p.includes('Род.п.') || p.includes('Дат.п.') || p.includes('Вин.п.') || p.includes('Зват.п.') || p.includes('Им.-Вин.п.')) {
      const cases = [];
      if (p.includes('Им.')) cases.push('nom');
      if (p.includes('Род.')) cases.push('gen');
      if (p.includes('Дат.')) cases.push('dat');
      if (p.includes('Вин.')) cases.push('acc');
      if (p.includes('Зват.')) cases.push('voc');
      caseVal = cases.length === 1 ? cases[0] : cases;
    }
  }
  
  return { pos, gender, number, case: caseVal };
}

